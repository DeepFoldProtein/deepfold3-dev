def _get_closest(length: int, choices: list[int]) -> int | None:
    """Find the closest value in a sorted list. Returns None if too far below minimum."""
    LOWER_MARGIN = 0.15
    if length < choices[0] * (1 - LOWER_MARGIN):
        return None
    if length > choices[-1]:
        return choices[-1]

    left, right = 0, len(choices) - 1
    while left < right:
        mid = (left + right) // 2
        if choices[mid] < length:
            left = mid + 1
        else:
            right = mid

    if left == 0:
        return choices[left]
    if abs(choices[left] - length) < abs(choices[left - 1] - length):
        return choices[left]
    return choices[left - 1]


def _is_cuda_backend() -> bool:
    if not HAS_TRITON:
        return True  # default assumption
    return triton.runtime.driver.active.get_current_target().backend == "cuda"


def calculate_config_layernorm_linear(
    M: int, N: int, K: int, mode: int
) -> tuple[tuple, tuple] | tuple | None:
    """Look up optimal Triton block config for given (M, N, K) shape.

    Args:
        M: Batch dim (flattened rows).
        N: Output features.
        K: Input features.
        mode: 0=fwd config only, 1=bwd config only, 2=both (fwd, bwd) tuple.

    Returns:
        Config tuple(s) or None if no suitable config found (fallback to PyTorch).
    """
    if _is_cuda_backend():
        common, m_for_nk, structured = _CUDA_COMMON, _CUDA_M_FOR_NK, _CUDA_STRUCTURED
    else:
        common, m_for_nk, structured = _HIP_COMMON, _HIP_M_FOR_NK, _HIP_STRUCTURED

    res = common.get((M, N, K))
    if res is not None:
        return res[mode] if mode < 2 else res

    m_list = m_for_nk.get((N, K))
    if m_list is None:
        return None

    closest_m = _get_closest(M, m_list)
    if closest_m is None:
        return None

    res = structured.get((closest_m, N, K))
    if res is None:
        return None
    return res[mode] if mode < 2 else res


