def res_name_to_type(name: str) -> int:
    """Convert residue name (3-letter or short nucleic code) to type index."""
    if name in RES_TYPE_ORDER:
        return RES_TYPE_ORDER[name]
    mapped = _NONSTANDARD_TO_STANDARD.get(name)
    if mapped is not None and mapped in RES_TYPE_ORDER:
        return RES_TYPE_ORDER[mapped]
    return 20  # UNK


